import assert from 'node:assert/strict'
import { createDemoProgress,demoView,changeDemoWeight,changeDemoMeal,setDemoComplete } from '../src/demo/progressDemoData.js'

const data=createDemoProgress(Date.parse('2026-11-03T16:00:00Z'))
assert.equal(data.profile.nombre,'Lucía Demo')
assert.equal(data.weights.length,84)
assert.equal(data.meals.length,168)
const original=JSON.stringify(data),view=demoView(data)
assert.equal(view.balance.covered,28)
assert.equal(view.projection.ready,true)
assert.equal(view.projection.version,'observed-weekly-v2')
assert.equal(view.comparison.sufficient,true)
assert.equal(data.weights.at(-1).weight_kg,79.51)
const changed=changeDemoMeal(data,500)
assert.equal(demoView(changed).balance.covered,27,'Una corrección invalida completitud')
assert.equal(demoView(changed).projection.ready,false)
const confirmed=setDemoComplete(changed,'meals_complete',true)
assert.equal(demoView(confirmed).balance.covered,28)
assert.equal(demoView(confirmed).balance.accumulated,view.balance.accumulated-550)
assert.equal(demoView(setDemoComplete(data,'activity_complete',false)).balance.covered,27)
assert.equal(changeDemoWeight(data,78).weights.at(-1).weight_kg,78)
assert.equal(demoView(changeDemoWeight(data,78)).projection.goalEstimate,null,'Último día ya alcanzó la meta')
assert.throws(()=>changeDemoWeight(data,-1))
assert.throws(()=>changeDemoMeal(data,''))
assert.throws(()=>setDemoComplete(data,'unknown',true))
assert.equal(JSON.stringify(data),original,'La simulación no altera sus datos anteriores')
assert.deepEqual(createDemoProgress(data.now),data,'Restablecer reconstruye el escenario inicial')
assert.equal(demoView(createDemoProgress(Date.parse('2026-01-01T02:00:00Z'))).projection.ready,true,'Respeta cierre de día local y cambio de año')
console.log('OK: perfil ficticio, 84 días, cálculo real, correcciones, completitud y restablecimiento sin persistencia.')
