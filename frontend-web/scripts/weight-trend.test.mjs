import assert from 'node:assert/strict'
import { compareWeightTrend } from '../src/lib/weightTrendData.js'
import { periodDays } from '../src/lib/balanceData.js'
const days=periodDays('2020-01-01','2020-01-28'),now=Date.parse('2020-02-01T00:00Z')
const weights=days.map((day,i)=>({id:String(i),measured_at:`${day}T12:00Z`,weight_kg:80}))
const energy=(value=-400)=>({rows:days.map(day=>({day,eligible:true,balance:value}))})
const run=(ws=weights,balance=energy(),start=days[0],end=days.at(-1),zone='UTC',time=now)=>compareWeightTrend(ws,balance,start,end,zone,time)
let result=run()
assert.equal(result.sufficient,true);assert.equal(result.persistent,'deficit');assert.equal(result.trend[0].kg,null);assert.equal(result.trend[2].kg,80)
assert.equal(run(weights,energy(400)).persistent,'surplus')
assert.equal(run(weights,energy(20)).persistent,null)
const losing=weights.map((w,i)=>({...w,weight_kg:80-i*0.05}))
assert.equal(run(losing).persistent,null)
const spike=losing.map((w,i)=>({...w,weight_kg:w.weight_kg+(i===20?8:0)}))
assert.equal(run(spike).persistent,null,'Una subida aislada no activa discrepancia')
assert.ok(run(spike).trend[20].kg<80)
const irregular=weights.filter((w,i)=>[0,2,6,7,10,13,14,17,20,21,23,27].includes(i))
result=run(irregular);assert.equal(result.sufficient,true);assert.equal(result.observed.length,12);assert.equal(result.trend.length,12,'No crear puntos en días sin pesajes')
assert.equal(run(irregular.filter((w,i)=>i!==0)).sufficient,false)
const duplicates=[...irregular,...Array.from({length:20},(_,i)=>({...weights[0],id:`extra${i}`}))]
assert.equal(run(duplicates).daily.length,12)
assert.equal(run(Array.from({length:20},(_,i)=>({...weights[0],id:String(i)}))).sufficient,false,'Repetir un día no sustituye días diferentes')
const incomplete=energy();incomplete.rows[10].eligible=false
assert.equal(run(weights,incomplete).sufficient,false)
assert.equal(run([],energy()).message,'Datos insuficientes')
assert.equal(run(weights,energy(),days[0],days[6]).sufficient,false)
assert.equal(run(weights,energy(),days[0],days.at(-1),'UTC',Date.parse('2020-01-28T20:00Z')).sufficient,false)
const changed=[...weights,{id:'future',measured_at:'2030-01-01T12:00Z',weight_kg:20},{id:'bad',measured_at:'bad',weight_kg:80}]
assert.equal(run(changed).observed.length,28)
const oneBlock=weights.map((w,i)=>({...w,weight_kg:i<14?80:80-(i-14)*0.1}))
assert.equal(run(oneBlock).persistent,null,'Una sola quincena discordante no es persistencia')
const zoned=run([{id:'a',measured_at:'2020-01-02T01:00Z',weight_kg:80}],energy(),days[0],days.at(-1),'America/La_Paz')
assert.equal(zoned.observed[0].day,'2020-01-01')
const sameDay=[{id:'a',measured_at:'2020-01-01T12:00Z',weight_kg:80},{id:'b',measured_at:'2020-01-01T14:00Z',weight_kg:82}]
assert.equal(run(sameDay).daily[0].kg,81)
const repeated=run([...sameDay,{...sameDay[1]}])
assert.equal(repeated.daily[0].kg,81,'Una copia del mismo ID no inclina la mediana')
assert.equal(repeated.observed.length,2);assert.equal(repeated.duplicates,1)
assert.ok(repeated.warnings.some(w=>w.includes('copias')))
const conflict=run([...weights,{...weights[0],weight_kg:90}])
assert.equal(conflict.sufficient,false);assert.equal(conflict.persistent,null)
assert.ok(conflict.issues.some(issue=>issue.includes('contradictorias')))
assert.equal(conflict.observed.some(w=>w.id===weights[0].id),false)
const malformed=run([...weights,null,{id:'bad-weight',measured_at:'2020-01-02T08:00Z',weight_kg:900}])
assert.equal(malformed.discarded,2)
assert.equal(malformed.daily.length,28)
assert.ok(malformed.warnings.length)
const repeatedEnergy=energy();repeatedEnergy.rows.push({...repeatedEnergy.rows[0]})
assert.equal(run(weights,repeatedEnergy).sufficient,true,'Una copia de un día energético no suma días')
const missingDay=energy();missingDay.rows.splice(3,1);missingDay.rows.push({...missingDay.rows[0]})
assert.equal(run(weights,missingDay).blocks[0].covered,13)
assert.equal(run(weights,missingDay).sufficient,false,'Catorce filas no sustituyen catorce fechas distintas')
const badEnergy=energy();badEnergy.rows[0].balance=NaN
assert.equal(run(weights,badEnergy).sufficient,false)
const conflictEnergy=energy();conflictEnergy.rows.push({...conflictEnergy.rows[0],balance:400})
assert.equal(run(weights,conflictEnergy).sufficient,false)
assert.ok(run(weights,conflictEnergy).issues.some(issue=>issue.includes('contradictorias')))
const sourceBalance=energy(),originals=JSON.stringify({weights,balance:sourceBalance})
run(weights,sourceBalance)
assert.equal(JSON.stringify({weights,balance:sourceBalance}),originals,'La tendencia no corrige registros originales')
const asymmetric=[...sameDay,{id:'c',measured_at:'2020-01-02T12:00Z',weight_kg:70},{id:'d',measured_at:'2020-01-03T12:00Z',weight_kg:72}]
assert.equal(run(asymmetric).trend.at(-1).kg,72,'La mediana móvil da el mismo peso a cada día')
const skipped=compareWeightTrend([],{rows:[]},'2011-12-03','2011-12-30','Pacific/Apia',now)
assert.equal(skipped.sufficient,false)
assert.ok(skipped.issues.some(issue=>issue.includes('día inexistente')))
console.log('OK: medianas, fechas irregulares, mínimos, días faltantes, duplicados, fluctuación aislada, discrepancias persistentes y zonas.')
const farApart=run([{id:'a',measured_at:'2020-01-01T12:00Z',weight_kg:80},{id:'b',measured_at:'2020-01-14T12:00Z',weight_kg:81},{id:'c',measured_at:'2020-01-28T12:00Z',weight_kg:82}])
assert.ok(farApart.trend.every(p=>p.kg==null),'Tres pesajes lejanos no forman una ventana de siete días')
const reversed=run([...weights].reverse());assert.deepEqual(reversed.trend,run().trend)
const extra=run([{id:'outside',measured_at:'2019-12-31T12:00Z',weight_kg:10},...weights])
assert.equal(extra.observed.length,28);assert.equal(extra.trend[0].kg,null,'El periodo no toma pesajes previos ni futuros')
