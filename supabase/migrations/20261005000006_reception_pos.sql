-- Módulo de recepción: catálogo POS, ventas y gastos operativos.
-- La cuenta de recepción puede vender y registrar gastos; solo admin mantiene
-- el catálogo y el inventario.

create table if not exists public.pos_products (
  id uuid primary key default gen_random_uuid(),
  nombre text not null unique check (length(trim(nombre)) between 1 and 100),
  costo_compra numeric(10, 2) not null default 0 check (costo_compra >= 0),
  precio numeric(10, 2) not null check (precio > 0),
  stock integer not null default 0 check (stock >= 0),
  stock_minimo integer not null default 0 check (stock_minimo >= 0),
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.pos_sales (
  id uuid primary key default gen_random_uuid(),
  cashier_id uuid not null references auth.users (id),
  metodo_pago text not null check (metodo_pago in ('qr', 'efectivo', 'transferencia', 'tarjeta', 'yape_plin')),
  total numeric(12, 2) not null check (total > 0),
  receipt_number bigint generated by default as identity unique,
  created_at timestamptz not null default now()
);

create index if not exists idx_pos_sales_created_at on public.pos_sales (created_at);

create table if not exists public.pos_sale_items (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null references public.pos_sales (id) on delete cascade,
  product_id uuid not null references public.pos_products (id),
  product_name text not null,
  unit_price numeric(10, 2) not null check (unit_price > 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(12, 2) not null check (line_total > 0)
);

create index if not exists idx_pos_sale_items_sale on public.pos_sale_items (sale_id);

create table if not exists public.operating_expenses (
  id uuid primary key default gen_random_uuid(),
  created_by uuid not null default auth.uid() references auth.users (id),
  concepto text not null check (length(trim(concepto)) between 1 and 160),
  categoria text not null check (categoria in ('Sueldos', 'Alquiler', 'Servicios', 'Insumos', 'Mantenimiento', 'Otros')),
  metodo_pago text not null default 'efectivo' check (metodo_pago in ('qr', 'efectivo', 'transferencia', 'tarjeta', 'yape_plin')),
  monto numeric(12, 2) not null check (monto > 0),
  created_at timestamptz not null default now()
);

create index if not exists idx_operating_expenses_created_at
  on public.operating_expenses (created_at);

alter table public.pos_products enable row level security;
alter table public.pos_sales enable row level security;
alter table public.pos_sale_items enable row level security;
alter table public.operating_expenses enable row level security;

