create or replace function public.register_pos_sale(
  p_payment_method text,
  p_items jsonb
)
returns public.pos_sales
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
  v_sale public.pos_sales;
  v_item jsonb;
  v_product public.pos_products;
  v_quantity integer;
  v_total numeric(12, 2) := 0;
begin
  if v_email not in ('recepcion@ironforge.com', 'admin@ironforge.com')
     or auth.uid() is null then
    raise exception 'Solo recepción o administración puede registrar ventas';
  end if;
  if p_payment_method not in ('qr', 'efectivo', 'transferencia', 'tarjeta', 'yape_plin') then
    raise exception 'Método de pago no válido';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'La venta debe incluir al menos un producto';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if jsonb_typeof(v_item -> 'quantity') <> 'number'
       or (v_item ->> 'quantity') !~ '^[0-9]+$' then
      raise exception 'La cantidad de cada producto debe ser un entero positivo';
    end if;
    v_quantity := (v_item ->> 'quantity')::integer;
    if v_quantity < 1 then
      raise exception 'La cantidad de cada producto debe ser un entero positivo';
    end if;
    select * into v_product
      from public.pos_products
     where id = (v_item ->> 'product_id')::uuid
       and activo = true
     for update;
    if not found then
      raise exception 'Uno de los productos no existe o está inactivo';
    end if;
    if v_product.stock < v_quantity then
      raise exception 'Stock insuficiente para el producto %', v_product.nombre;
    end if;
    v_total := v_total + (v_product.precio * v_quantity);
  end loop;

  insert into public.pos_sales (cashier_id, metodo_pago, total)
  values (auth.uid(), p_payment_method, v_total)
  returning * into v_sale;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_quantity := (v_item ->> 'quantity')::integer;
    select * into v_product
      from public.pos_products
     where id = (v_item ->> 'product_id')::uuid
       and activo = true;
    insert into public.pos_sale_items (
      sale_id, product_id, product_name, unit_price, quantity, line_total
    )
    values (
      v_sale.id, v_product.id, v_product.nombre, v_product.precio,
      v_quantity, v_product.precio * v_quantity
    );
    update public.pos_products
       set stock = stock - v_quantity,
           updated_at = now()
     where id = v_product.id;
  end loop;

  return v_sale;
end;
$$;

revoke all on function public.register_pos_sale(text, jsonb) from anon;
revoke all on function public.register_pos_sale(text, jsonb) from public;
grant execute on function public.register_pos_sale(text, jsonb) to authenticated;
